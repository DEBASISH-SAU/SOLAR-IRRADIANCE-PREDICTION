# Battery parameters
battery = 5  # capacity
soc = 2      # initial state
soc_list = []

grid_import = []
grid_export = []

for i in range(len(pv_power)):
    surplus = pv_power[i] - load[i]

    if surplus > 0:
        charge = min(surplus, battery - soc)
        soc += charge
        grid_export.append(surplus - charge)
        grid_import.append(0)
    else:
        discharge = min(abs(surplus), soc)
        soc -= discharge
        grid_import.append(abs(surplus) - discharge)
        grid_export.append(0)

    soc_list.append(soc)

